/** منظمة «حجوزات» تاخذ هوكات الحجوزات، والباقي هوكات المنيو. */
export const hookLibraryKey = (orgId: string | null | undefined): HookLibraryKey =>
  orgId === "00000000-0000-0000-0000-000000000002" ? "bookings" : "menu";

export const hookLibraryFor = (orgId: string | null | undefined) => HOOK_LIBRARIES[hookLibraryKey(orgId)];

/** عينة عشوائية من الهوكات تُعطى للذكاء الاصطناعي كأمثلة للأسلوب. */
export function sampleHooks(orgId: string | null | undefined, count = 15): string[] {
  const list = [...hookLibraryFor(orgId).hooks];
  for (let i = list.length - 1; i > 0; i--) {
    const j = Math.floor(Math.random() * (i + 1));
    [list[i], list[j]] = [list[j], list[i]];
  }
  return list.slice(0, count).map((h) => h.text);
}
