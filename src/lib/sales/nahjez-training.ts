import { CHALLENGES, CONTACT_FLOW, INTERESTED_FLOW, LOYALTY, MATCHING, NOTES, RESULTS, SELL_PATH, SUPPORT_TEXT, TIERS } from "./nahjez-content";

const bullets = (items: string[]) => items.map((i) => `- ${i}`).join("\n");

function buildKnowledge(): string {
  const tiers = TIERS.map(
    (t) =>
      `- **${t.name}${t.recommended ? " (الموصى بها)" : ""}:** ${t.monthly} ريال شهرياً أو ${t.yearly} ريال سنوياً (توفير ${t.save} ريال بالسنوي)\n  ${t.note}`
  ).join("\n");

  const features = NOTES.map(
    (n) => `#### ${n.title} — باقة ${n.pkg}
${n.short}
${bullets(n.details)}
- **ألم العميل:** ${n.pain}
- **جمل إقناع:** ${n.hooks.join(" / ")}
- **اعتراض متوقع:** «${n.objection.q}» ← الرد: ${n.objection.a}
- **النتيجة:** ${n.metric}
- **تناسب:** ${n.fit}`
  ).join("\n\n");

  const matching = MATCHING.map((m) => `- ${m.type} ← **${m.pkg}**`).join("\n");
  const results = RESULTS.map((r) => `- **${r.impact}:** ${r.idea} (التطبيق: ${r.how})`).join("\n");
  const challenges = CHALLENGES.map((c) => `- **${c.challenge}** ← ${c.solution}`).join("\n");
  const sellPath = SELL_PATH.map((s) => `${s.n}. **${s.t}:** ${s.d}`).join("\n");
  const flow = CONTACT_FLOW.map((s) => `${s.n}. **${s.title}** — ${s.goal}\n   مثال مكالمة: «${s.call}»`).join("\n");
  const interested = INTERESTED_FLOW.map((s) => `${s.n}. **${s.title}** — ${s.goal}`).join("\n");

  return `## معلومات المنتج — منصة «نحجز هب» (NEHGZ HUB)

### المفهوم:
منصة سعودية لإدارة الحجوزات للصالونات ومراكز التجميل والسبا: صفحة/موقع باسم المركز، حجز أونلاين ٢٤/٧، تأكيد وتذكير بالواتساب، مدفوعات وعربون بدون عمولة، لوحة تحكم وتقارير، متجر وفروع، وبطاقات هدايا وولاء.
${SUPPORT_TEXT}

### الباقات والأسعار (المعتمدة في عرض العميل — لا تذكر غيرها):
${tiers}
- **مهم:** الباقة الأساسية **بدون نظام حجوزات** — موقع يعرض الخدمات فقط. أي عميل يبي حجز أونلاين أو تذكير أو عربون أو هدايا/ولاء = نمو الأعمال.

### المميزات بالتفصيل (من الخريطة التفاعلية):
${features}

### الميزة التسويقية البارزة — ${LOYALTY.title}:
${LOYALTY.why}
${bullets(LOYALTY.bullets)}

### مطابقة نوع العميل بالباقة:
${matching}

### النتائج الملموسة اللي يعرضها المندوب:
${results}

### مسار البيع المختصر:
${sellPath}

### تسلسل الاتصال المعتمد (٨ خطوات):
${flow}

### مسار العميل المهتم (بعد ما يبدي اهتمام):
${interested}

### التحديات والاعتراضات والردود المعتمدة:
${challenges}`;
}

